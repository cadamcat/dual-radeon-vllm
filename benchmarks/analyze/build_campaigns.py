#!/usr/bin/env python3
"""build_campaigns.py — the index of every experiment directory, generated.

`benchmarks/README.md` carried a hand-typed table of campaigns, and by
2026-09-03 it named eighteen of the forty-two directories that have a README.
A table nobody regenerates is a second source of truth that only ever falls
behind, so this one is derived: every directory under benchmarks/ with a
README.md is a row, its title is that README's first heading, and the row
says whether the directory holds measurements the projections read.

    python3 build_campaigns.py            # write ../CAMPAIGNS.md
    python3 build_campaigns.py --check    # fail if the committed file is stale
"""
import argparse
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
B = os.path.normpath(os.path.join(HERE, ".."))
OUT = os.path.join(B, "CAMPAIGNS.md")
SKIP_DIRS = {"__pycache__", "logs", "serve-logs", "traces", "logs-nosplitkv", "logs-attempt1",
             "analyze", "harness", "prompts"}

sys.path.insert(0, HERE)
from build_prefill import SOURCES  # noqa: E402

PROJECTED = {os.path.dirname(s["file"]) for s in SOURCES if os.path.dirname(s["file"])}

# where a directory sits, by the machine family its name carries
GROUPS = [("The Radeon pair, and one of its cards", lambda d: not d.startswith(("cuda-", "modal-"))
           and not d.startswith("allreduce")),
          ("Rented and granted NVIDIA cards", lambda d: d.startswith(("cuda-", "modal-"))),
          ("The collective, on every pair measured", lambda d: d.startswith("allreduce"))]


def title_of(readme):
    for line in open(readme, encoding="utf-8"):
        if line.startswith("# "):
            return line[2:].strip()
    return "(no title)"


def rows_in(path):
    """measurement rows in a results file, or None where there is no such file"""
    if not os.path.exists(path):
        return None
    n = 0
    for line in open(path, encoding="utf-8"):
        line = line.strip()
        if not line:
            continue
        try:
            r = json.loads(line)
        except Exception:
            continue
        if r.get("kind") in ("decode", "prefill", "allreduce"):
            n += 1
    return n


def scan():
    out = []
    for root, dirs, files in os.walk(B):
        dirs[:] = sorted(d for d in dirs if d not in SKIP_DIRS and not d.startswith("."))
        if root == B or "README.md" not in files:
            continue
        rel = os.path.relpath(root, B)
        out.append({"dir": rel, "title": title_of(os.path.join(root, "README.md")),
                    "rows": rows_in(os.path.join(root, "results.jsonl")),
                    "projected": rel in PROJECTED,
                    "date": (re.search(r"(\d{4}-\d{2}-\d{2})", rel) or [None, None])[1]})
    return sorted(out, key=lambda r: (r["date"] or "", r["dir"]))


def render(items):
    lines = ["# Every experiment directory under benchmarks/, from the tree", "",
             "Generated by `analyze/build_campaigns.py`; edit a directory's README, not this.",
             "One row per directory that carries a README. *projected* marks the directories",
             "whose `results.jsonl` the two cross-machine projections (`prefill.jsonl`,",
             "`decode.jsonl`) are built from; a directory without a results file is a",
             "finding, a preflight, or a sweep that writes its own files.", ""]
    for name, pred in GROUPS:
        chosen = [r for r in items if pred(r["dir"])]
        if not chosen:
            continue
        lines += [f"## {name}", "", "| directory | what its README says it is | rows | projected |",
                  "|---|---|--:|:--:|"]
        for r in chosen:
            rows = "—" if r["rows"] is None else str(r["rows"])
            lines.append(f"| [`{r['dir']}/`]({r['dir']}/README.md) | {r['title']} | {rows} | "
                         f"{'yes' if r['projected'] else ''} |")
        lines.append("")
    n = len(items)
    lines.append(f"{n} directories; {sum(1 for r in items if r['projected'])} feed the projections.")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(scan())
    if a.check:
        have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if have != text:
            print("CAMPAIGNS.md is stale; re-run build_campaigns.py", file=sys.stderr)
            return 1
        print(f"CAMPAIGNS.md matches the tree: {text.count('| [`')} directories")
        return 0
    open(OUT, "w", encoding="utf-8").write(text)
    print(f"wrote {OUT}: {text.count('| [`')} directories")
    return 0


if __name__ == "__main__":
    sys.exit(main())
